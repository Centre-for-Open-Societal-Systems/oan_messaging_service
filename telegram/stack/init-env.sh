#!/usr/bin/env sh
# Generate telegram/stack/.env: every secret of the local stack, random, made on this
# machine, git-ignored, mode 600. Never reuse these values anywhere else.
# If .env already exists, only keys it lacks are added (existing values are kept).
set -eu
cd "$(dirname "$0")"
py() { python3 -c "$1"; }
hex() { py "import secrets; print(secrets.token_hex($1))"; }
urlsafe() { py "import secrets, string; a=string.ascii_letters+string.digits+'_-'; print(''.join(secrets.choice(a) for _ in range($1)))"; }
b64() { py 'import base64, os; print(base64.b64encode(os.urandom(32)).decode())'; }
umask 077
new=$(mktemp)
trap 'rm -f "$new"' EXIT
broadcast_token=$(urlsafe 48)
cat > "$new" <<ENV
TG_BOT_TOKEN=$(py 'import secrets; print(str(secrets.randbelow(9 * 10**9) + 10**9))'):$(urlsafe 35)
TG_WEBHOOK_SECRET=$(urlsafe 64)
CONTACT_REF_KEY=$(b64)
BOT_FINGERPRINT_KEY=$(b64)
BOT_DATA_KEY=$(b64)
BOT_BROADCAST_TOKEN=$broadcast_token
BOT_BROADCAST_TOKEN_SHA256=$(printf '%s' "$broadcast_token" | python3 -c 'import hashlib, sys; print(hashlib.sha256(sys.stdin.buffer.read()).hexdigest())')
OAN_BOT_DB_PW=$(hex 16)
OAN_STUBS_CLIENT_ID=bot-services
OAN_STUBS_CLIENT_SECRET=$(urlsafe 48)
OAN_PG_SUPERUSER_PW=$(hex 16)
OAN_OWNER_PW=$(hex 16)
OAN_RUNTIME_PW=$(hex 16)
OAN_MSG_CONTENT_KEYS=v1:$(b64)
OAN_MSG_CONTENT_KEY_CURRENT=v1
OAN_MSG_FINGERPRINT_KEYS=k1:$(b64)
OAN_MSG_FINGERPRINT_KEY_CURRENT=k1
OAN_MSG_CREDENTIAL_PEPPER=$(b64)
SMS8028_CLIENT_SECRET=$(urlsafe 40)
OAN_MSG_BOT_SERVICES_TOKEN=
OAN_MSG_SMS_TEST_TOKEN=
ENV
if [ ! -e .env ]; then
  { echo "# Generated by init-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Local stack only. Do not commit."
    echo "# OAN_MSG_BOT_SERVICES_TOKEN and OAN_MSG_SMS_TEST_TOKEN are filled by up.sh."
    cat "$new"; } > .env
  echo "wrote telegram/stack/.env (mode 600, git-ignored)"
  exit 0
fi
# Existing .env: add only the keys it lacks. A pair (token and its hash) is added together.
added=$(python3 - "$new" <<'PY'
import re, sys
have = {l.split("=", 1)[0] for l in open(".env") if re.match(r"^[A-Z0-9_]+=", l)}
lines = [l for l in open(sys.argv[1]) if l.strip()]
pairs = {"BOT_BROADCAST_TOKEN": "BOT_BROADCAST_TOKEN_SHA256", "BOT_BROADCAST_TOKEN_SHA256": "BOT_BROADCAST_TOKEN"}
keep = []
for l in lines:
    k = l.split("=", 1)[0]
    if k in have and not (k in pairs and pairs[k] not in have):
        continue
    keep.append(l)
if keep:
    with open(".env", "a") as f:
        f.write("# Added by init-env.sh\n" + "".join(keep))
print(" ".join(l.split("=", 1)[0] for l in keep))
PY
)
if [ -n "$added" ]; then echo ".env existed; added: $added"; else echo ".env exists and is complete"; fi
